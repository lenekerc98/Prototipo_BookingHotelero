const listeners = new Set<() => void>();

function readStoredLang(): Lang {
  try {
    return localStorage.getItem(STORAGE_KEY) === "en" ? "en" : "es";
  } catch {
    return "es";
  }
}

let currentLang: Lang = readStoredLang();

if (typeof document !== "undefined") {
  document.documentElement.lang = currentLang;
}

export function getLang(): Lang {
  return currentLang;
}

export function setLang(lang: Lang): void {
  if (lang === currentLang) return;
  currentLang = lang;
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    // Sin storage disponible: el idioma dura solo la sesión actual
  }
  if (typeof document !== "undefined") {
    document.documentElement.lang = lang;
  }
  listeners.forEach(fn => fn());
}

function subscribe(fn: () => void): () => void {
  listeners.add(fn);
  return () => {
    listeners.delete(fn);
  };
}

/** Traduce un texto en español (clave) al idioma activo y reemplaza los marcadores {nombre}. */
export function tx(text: string, vars?: Record<string, string | number>): string {
  let out = currentLang === "en" ? (EN[text] ?? text) : text;
  if (vars) {
    for (const key of Object.keys(vars)) {
      out = out.split(`{${key}}`).join(String(vars[key]));
    }
  }
  return out;
}

// Descripciones del Catastro Turístico: la mayoría siguen esta plantilla.
const DESC_RE = /^Establecimiento oficial de hospedaje adscrito al Catastro Turístico de Manta \((Hotel|Hostal|Hostería) - (\d) Estrellas?\)\. Ubicado en (Manta - [^,]+), ofrece atención cordial, excelente conectividad y tarifas directas garantizadas con confirmación de reserva inmediata\.$/;
const CLASS_EN: Record<string, string> = { "Hotel": "Hotel", "Hostal": "Hostel", "Hostería": "Inn" };

/** Descripción de un alojamiento. Si sigue la plantilla se arma en inglés; si no, usa el diccionario. */
export function txDesc(text: string): string {
  if (currentLang !== "en") return text;
  const m = DESC_RE.exec(text);
  if (!m) return tx(text);
  return `Official accommodation listed in the Manta tourism registry (${CLASS_EN[m[1]]}, ${m[2]}-star). Located in ${tx(m[3])}, with friendly service, excellent connectivity and direct rates guaranteed with instant booking confirmation.`;
}

/** Suscribe el componente al idioma (se vuelve a renderizar al cambiar) y devuelve tx(). */
export function useI18n(): typeof tx {
  useSyncExternalStore(subscribe, getLang, getLang);
  return tx;
}

/** Idioma activo, suscrito a cambios. */
export function useLang(): Lang {
  return useSyncExternalStore(subscribe, getLang, getLang);
}

// Locale para Intl/toLocaleDateString según el idioma activo (solo visualización).
export function locale(): string {
  return getLang() === "en" ? "en-US" : "es-EC";
}
